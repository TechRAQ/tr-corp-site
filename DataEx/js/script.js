//Resize window
function resize() {
    if ($(window).width() < 700) {
      $('.onhovveds').addClass('onhovvedssss');
    }
  }
  resize()





$('.onhovvedssss').click( function(){
    $('.cassedsstudess').addClass('case_stucli')
    $('.close_side').addClass('mobclosee')
})

$('.close_side').click( function(){
    $('.cassedsstudess').removeClass('case_stucli')  
    $('.close_side').removeClass('mobclosee')
})